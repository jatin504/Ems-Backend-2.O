def get_bess_schedule(timestamp, load_mw):
    """
    Return the BESS schedule applicable for the given timestamp.

    Parameters
    ----------
    timestamp : datetime | str
        Present timestamp.

    load_mw : float
        Current forecast/actual load in MW.

    Returns
    -------
    dict
        Applicable BESS schedule.
    """

    if isinstance(timestamp, str):
        timestamp = datetime.fromisoformat(timestamp)

    current_time = timestamp.time()

    selected_schedule = BESS_SCHEDULE[0]

    for schedule in BESS_SCHEDULE:
        if current_time >= schedule["time"]:
            selected_schedule = schedule
        else:
            break

    return {
        "timestamp": timestamp,
        "load_mw": load_mw,
        "schedule_time": selected_schedule["time"].strftime("%H:%M"),
        "planned_bess": selected_schedule["planned_bess"],
        "required_reserve_pct": selected_schedule["required_reserve_pct"],
        "target_soc_pct": selected_schedule["target_soc_pct"],
    }

"""Supervise one primary API and optional read workers; generate HAProxy config.

Does not start HAProxy, main.py, databases, or alter the machine's services.
"""
import argparse
from contextlib import ExitStack
import json
import logging
import os
from pathlib import Path
import re
import signal
import socket
import subprocess
import sys
import time

from dotenv import dotenv_values, load_dotenv
from filelock import FileLock, Timeout

from api_scaling import READ_POST_PATHS, READ_PREFIXES

ROOT = Path(__file__).resolve().parent
logger = logging.getLogger("api-cluster")


def load_settings(path, instances=None):
    config = json.loads(Path(path).read_text(encoding="utf-8"))
    if instances is not None:
        config["instances"] = instances
    for name, low, high in (("instances", 1, 65535), ("first_api_port", 1, 65535),
                            ("proxy_port", 1, 65535), ("maxconn", 1, 100000)):
        value = config.get(name)
        if type(value) is not int or not low <= value <= high:
            raise ValueError(f"{name} must be an integer from {low} to {high}")
    ports = range(config["first_api_port"], config["first_api_port"] + config["instances"])
    if ports.stop > 65536 or config["proxy_port"] in ports:
        raise ValueError("API/proxy ports overlap or exceed 65535")
    # These ports belong to the user's frontend services.
    if {4445, 5000}.intersection(ports) or config["proxy_port"] in {4445, 5000}:
        raise ValueError("Ports 4445 and 5000 are reserved for the frontends")
    for name in ("api_host", "proxy_backend_host"):
        if not re.fullmatch(r"[A-Za-z0-9_.-]+", config.get(name, "")):
            raise ValueError(f"Invalid {name}; use an IPv4 address or hostname")
    pem = config.get("tls_pem", "")
    if not isinstance(pem, str) or (pem and not re.fullmatch(r"/[A-Za-z0-9_./-]+", pem)):
        raise ValueError("tls_pem must be empty or an absolute Linux path without spaces")
    return config


def render_haproxy(config):
    tls = config.get("tls_pem", "")
    bind = f"    bind :{config['proxy_port']}"
    if tls:
        bind += f" ssl crt {tls} alpn h2,http/1.1"
    lines = [
        "# Generated by run_api_cluster.py; edit cluster.json, not this file.",
        "# HTTP without tls_pem is for a trusted local test network only.",
        "global", "    log stdout format raw local0",
        "    user haproxy", "    group haproxy",
        f"    maxconn {config['maxconn']}",
        "    ssl-default-bind-options ssl-min-ver TLSv1.2",
        "    hard-stop-after 30s", "",
        "defaults", "    mode http", "    log global", "    option httplog",
        "    timeout connect 3s", "    timeout check 3s",
        "    timeout queue 10s", "    timeout http-request 15s",
        "    timeout http-keep-alive 10s", "    timeout client 1h",
        "    timeout server 60s", "    timeout tunnel 1h", "",
        "frontend ems", bind,
        "    acl private_path path,url_dec,lower -m reg ^/+stream/+internal(/|$) ^/+app(/|$)",
        "    http-request deny deny_status 403 if private_path",
        "    http-request del-header Forwarded",
        "    http-request del-header X-Forwarded-For",
        "    http-request del-header X-Forwarded-Host",
        "    http-request del-header X-Forwarded-Port",
        "    http-request set-header X-Forwarded-For %[src]",
        f"    http-request set-header X-Forwarded-Proto {'https' if tls else 'http'}",
        f"    http-request set-header X-Forwarded-Port {config['proxy_port']}",
        "    acl query_get method GET HEAD",
        "    acl query_post method POST",
        "    acl query_prefix path_beg " + " ".join(READ_PREFIXES),
        "    acl query_exact path " + " ".join(READ_POST_PATHS),
        "    acl stream_path path -i /stream /stream/",
        "    acl probe_path path /health /ping",
        "    use_backend ems_reads if query_get probe_path",
        "    use_backend ems_reads if query_get query_prefix",
        "    use_backend ems_reads if query_post query_exact",
        "    use_backend ems_stream if stream_path",
        "    default_backend ems_primary", "",
    ]
    host, port = config["proxy_backend_host"], config["first_api_port"]
    for backend in ("ems_primary", "ems_stream", "ems_reads"):
        lines.extend([
            f"backend {backend}", "    balance leastconn",
            "    retries 0",  # Do not replay ambiguous commands/mutations.
            "    option httpchk",
            "    http-check send meth GET uri /health/ready ver HTTP/1.1 hdr Host ems.internal",
            "    http-check expect status 200",
            "    default-server inter 5s fall 2 rise 2",
        ])
        if backend == "ems_stream":
            lines.append("    timeout server 1h")
        count = config["instances"] if backend == "ems_reads" else 1
        lines.extend(f"    server api{i + 1} {host}:{port + i} check"
                     for i in range(count))
        lines.append("")
    return "\n".join(lines)


def worker_environment(config, index):
    env = os.environ.copy()
    env.update(EMS_API_BIND=f"{config['api_host']}:{config['first_api_port'] + index}",
               EMS_API_ROLE="primary" if index == 0 else "read",
               EMS_API_INSTANCE=f"api{index + 1}", PYTHONUNBUFFERED="1")
    return env


def report_database_selection():
    """Report names only; never print connection credentials or the full .env."""
    role = os.getenv("DB_ROLE")
    key = "PRIMARY_DB_NAME" if role == "primary" else "STANDBY_DB_NAME"
    selected = os.getenv(key)
    file_value = dotenv_values(ROOT / ".env").get(key)
    logger.info("DB_ROLE=%s; selected %s=%s", role, key, selected)
    if selected != file_value and file_value is not None:
        logger.warning(
            "%s environment override=%r differs from .env=%r. "
            "Environment variables take precedence; clear stale shell overrides before testing.",
            key, selected, file_value)


def preflight(config):
    data = os.getenv("EMS_DATA_DIR", "")
    root = Path(data).expanduser().resolve() if data else None
    if root is None or not (root / "config/device_config.json").is_file():
        raise ValueError("EMS_DATA_DIR must point to the existing EMS data folder")
    # Resolve once so every worker uses exactly the same directory.
    os.environ["EMS_DATA_DIR"] = str(root)
    # Check all ports before starting any child. Still bind normally in workers:
    # this is an error check, not a reservation against unrelated processes.
    for port in range(config["first_api_port"], config["first_api_port"] + config["instances"]):
        with socket.socket() as probe:
            if os.name == "nt":
                probe.setsockopt(socket.SOL_SOCKET, socket.SO_EXCLUSIVEADDRUSE, 1)
            probe.bind((config["api_host"], port))


def supervise(config):
    children = {}
    failures = {}
    next_start = {}
    started = {}
    stopping = False

    def stop(*_):
        nonlocal stopping
        stopping = True

    signal.signal(signal.SIGINT, stop)
    signal.signal(signal.SIGTERM, stop)
    try:
        while not stopping:
            now = time.monotonic()
            for index in range(config["instances"]):
                child = children.get(index)
                if child is not None and child.poll() is not None:
                    failures[index] = 1 if now - started[index] > 60 else failures.get(index, 0) + 1
                    if failures[index] >= 3:
                        raise ValueError(
                            f"api{index + 1} failed 3 times within short runs; stopping the cluster. "
                            "Fix the first worker error above before restarting.")
                    delay = min(30, 2 ** min(failures[index], 5))
                    next_start[index] = now + delay
                    logger.error("api%s exited (%s); restarting in %ss", index + 1, child.returncode, delay)
                    children.pop(index)
                if index not in children and now >= next_start.get(index, 0):
                    kwargs = {"creationflags": subprocess.CREATE_NEW_PROCESS_GROUP} if os.name == "nt" else {}
                    children[index] = subprocess.Popen(
                        [sys.executable, str(ROOT / "api_server.py")], cwd=ROOT,
                        env=worker_environment(config, index), **kwargs)
                    started[index] = now
                    logger.info("Started api%s PID=%s port=%s role=%s", index + 1,
                                children[index].pid, config["first_api_port"] + index,
                                "primary" if index == 0 else "read")
            time.sleep(0.25)
    finally:
        for child in children.values():
            if child.poll() is None:
                try:
                    child.send_signal(signal.CTRL_BREAK_EVENT if os.name == "nt" else signal.SIGTERM)
                except OSError:
                    pass
        deadline = time.monotonic() + 25
        for child in children.values():
            try:
                child.wait(timeout=max(0, deadline - time.monotonic()))
            except subprocess.TimeoutExpired:
                child.kill()
                child.wait()


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--config", type=Path, default=ROOT / "deploy/haproxy/cluster.json")
    parser.add_argument("--instances", type=int, help="Override JSON instance count for this run")
    parser.add_argument("--generate-only", action="store_true", help="Write proxy config without starting APIs")
    parser.add_argument("--output", type=Path, default=ROOT / "deploy/haproxy/generated.cfg")
    args = parser.parse_args()
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    load_dotenv(ROOT / ".env")
    try:
        config = load_settings(args.config, args.instances)
        if not args.generate_only:
            report_database_selection()
            preflight(config)
        # Prevent two supervisors from starting duplicate primary processes.
        lock_path = ROOT / "deploy/haproxy/cluster.lock"
        with ExitStack() as locks:
            locks.enter_context(FileLock(lock_path, timeout=0))
            if not args.generate_only:
                locks.enter_context(FileLock(Path(os.environ["EMS_DATA_DIR"]) / ".api-primary.lock", timeout=0))
            args.output.parent.mkdir(parents=True, exist_ok=True)
            args.output.write_text(render_haproxy(config), encoding="utf-8")
            logger.info("Wrote %s (%s API instance(s))", args.output, config["instances"])
            scheme = "https" if config.get("tls_pem") else "http"
            logger.info("Frontend endpoint: %s://<HAProxy-host>:%s (configured, NOT started by this launcher)",
                        scheme, config["proxy_port"])
            logger.info("Start/reload HAProxy separately with %s", args.output)
            logger.info("Internal SSE publisher target for main.py: EMS_INTERNAL_API_URL=http://127.0.0.1:%s",
                        config["first_api_port"])
            if not args.generate_only:
                supervise(config)
    except (ValueError, OSError, Timeout) as error:
        parser.exit(1, f"Cluster configuration/startup error: {error}\n")


if __name__ == "__main__":
    main()
